import hashlib
import json
import os
from typing import Literal

from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import Response
from pydantic import BaseModel, ConfigDict, Field, field_validator

from sap_cua.rag.schemas import DOMAINS, KnowledgeObject
from sap_cua.security import sanitize_data

router = APIRouter()


class Query(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    query: str = Field(min_length=1, max_length=4000)
    collections: list[str] | None = Field(default=None, min_length=1, max_length=19)

    @field_validator("collections")
    @classmethod
    def known_collections(cls, value):
        if value is not None and (set(value) - DOMAINS or len(set(value)) != len(value)):
            raise ValueError("Unknown or duplicate knowledge collections")
        return value


class PlanRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    requirement: str = Field(min_length=1, max_length=4000)
    backend: Literal["sandbox", "sap_api"] = "sandbox"


def service(request):
    instance = request.app.state.rag
    if instance is None:
        initializing = bool(os.getenv("SAP_CUA_DATABASE_URL")) and not getattr(
            request.app.state, "rag_error", None
        )
        raise HTTPException(
            503,
            "Knowledge initialization is unavailable. Check the database and embedding cache configuration."
            if getattr(request.app.state, "rag_error", None)
            else "Knowledge is initializing or not configured. SAP DEV setup remains available. "
            "Set SAP_CUA_DATABASE_URL to enable retrieval.",
            headers={"Retry-After": "2"} if initializing else None,
        )
    return instance


@router.get("/status")
def status(request: Request):
    r = service(request)
    return {
        "backend": "postgresql_pgvector",
        "scope": r.scope.model_dump(),
        "collections": r.store.counts(r.scope) if hasattr(r.store, "counts") else {},
        "embedding": r.retriever.embeddings.version,
        "reranker": r.retriever.reranker.version,
        "training_required": False,
    }


@router.post("/search")
def search(query: Query, request: Request):
    r = service(request)
    return {
        "hits": [
            hit.model_dump()
            for hit in r.retriever.search(query.query, r.scope, collections=query.collections)
        ]
    }


@router.post("/plans", status_code=201)
def plan(payload: PlanRequest, request: Request):
    r = service(request)
    return r.create_plan(payload.requirement, payload.backend).model_dump()


@router.post("/plans/{id}/run")
def execute(id: str, request: Request):
    try:
        return service(request).execute_plan(id)
    except KeyError as exc:
        raise HTTPException(404, "Plan not found") from exc
    except (ValueError, PermissionError) as exc:
        raise HTTPException(409, str(exc)) from exc


@router.get("/runs")
def runs(request: Request):
    return sanitize_data(service(request).runs())


@router.get("/metrics")
def metrics(request: Request):
    service(request)
    import json

    from sap_cua.engineering.telemetry import metrics_snapshot

    return json.loads(metrics_snapshot())


class KnowledgeRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    title: str = Field(min_length=1, max_length=200)
    content: str = Field(min_length=1, max_length=25000)
    source: str = Field(min_length=1, max_length=500)
    source_version: str = Field(default="1", min_length=1, max_length=100)
    collection: str = "sap_docs"
    approved: Literal[True]

    @field_validator("collection")
    @classmethod
    def text_collection(cls, value):
        if value not in DOMAINS - {"trajectories", "screenshots", "successful_solutions"}:
            raise ValueError(
                "Choose a text knowledge collection; execution memory is generated by verifiers"
            )
        return value


@router.post("/knowledge", status_code=201)
def ingest_knowledge(payload: KnowledgeRequest, request: Request):
    r = service(request)
    identity = hashlib.sha256((payload.source + "\0" + payload.title).encode()).hexdigest()[:24]
    document = KnowledgeObject(
        id="manual-" + identity,
        document_type="text",
        collection=payload.collection,
        topic=payload.title,
        title=payload.title,
        content=payload.content,
        source=payload.source,
        source_version=payload.source_version,
        customer_scope=r.scope.customer,
        tenant_scope=r.scope.tenant,
        security_classification="internal",
        approved=payload.approved,
        license="user-approved",
    )
    try:
        return r.ingestor.ingest(document, r.scope)
    except PermissionError as exc:
        raise HTTPException(403, "This role cannot add knowledge") from exc


@router.get("/runs/{id}")
def get_run(id: str, request: Request):
    record = service(request).get_run(id)
    if record is None:
        raise HTTPException(404, "Run not found")
    return sanitize_data(record)


@router.get("/runs/{id}/export")
def export_run(id: str, request: Request):
    record = get_run(id, request)
    filename = "sap-run-" + hashlib.sha256(id.encode()).hexdigest()[:12] + ".json"
    return Response(
        json.dumps(sanitize_data(record), indent=2),
        media_type="application/json",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
